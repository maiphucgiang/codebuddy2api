const messages: Record<Lang, Record<string, string>> = { zh, en };
/** Every key with its translation per language; tests check the maps that point into it. */
export const messageKeys = Object.keys(zh) as MessageKey[];
const STORAGE_KEY = "codebuddy2api.lang";
const LANG_EVENT = "codebuddy.lang";

export type LangPref = "system" | Lang;

function systemLang(): Lang {
  try {
    return navigator.language?.toLowerCase().startsWith("zh") ? "zh" : "en";
  } catch {
    return "zh";
  }
}
function savedPref(): LangPref {
  try {
    const value = localStorage.getItem(STORAGE_KEY);
    return value === "zh" || value === "en" ? value : "system";
  } catch {
    return "system";
  }
}
let currentPref: LangPref = "system";
export function serverPreference(value: unknown): LangPref {
  if (value === "zh" || value === "en") return value;
  return "system";
}
export function languagePreference(): LangPref {
  return currentPref;
}
export function chooseLanguage(pref: LangPref) {
  currentPref = pref;
  try {
    localStorage.setItem(STORAGE_KEY, pref);
  } catch {
    /* ignore */
  }
  window.dispatchEvent(new CustomEvent(LANG_EVENT, { detail: pref }));
}

let currentLang: Lang = "zh";
const LangContext = createContext<Lang>("zh");

export function translate(key: string, vars?: Record<string, string | number>): string {
  const template = messages[currentLang][key] ?? messages.zh[key] ?? key;
  return vars
    ? template.replace(/\{(\w+)\}/g, (name) => String(vars[name.slice(1, -1)] ?? name))
    : template;
}

// Global translator: the provider re-renders the whole tree on language
// change, so plain t() calls stay reactive without per-component hooks.
export const t = translate;
export function useLang(): Lang {
  return useContext(LangContext);
}
export function useT() {
  const lang = useLang();
  return useMemo(
    () => (key: string, vars?: Record<string, string | number>) => translate(key, vars),
    [lang],
  );
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [pref, setPref] = useState<LangPref>(() => {
    currentPref = savedPref();
    return currentPref;
  });
  const [system, setSystem] = useState<Lang>(systemLang);
  const lang = pref === "system" ? system : pref;
  currentLang = lang;
  useEffect(() => {
    document.documentElement.lang = lang === "en" ? "en" : "zh-CN";
  }, [lang]);
  useEffect(() => {
    const apply = (event: Event) => {
      const detail = (event as CustomEvent<string>).detail;
      if (detail === "zh" || detail === "en" || detail === "system") setPref(detail);
    };
    window.addEventListener(LANG_EVENT, apply);
    return () => window.removeEventListener(LANG_EVENT, apply);
  }, []);
  useEffect(() => {
    const sync = () => setSystem(systemLang());
    window.addEventListener("languagechange", sync);
    return () => window.removeEventListener("languagechange", sync);
  }, []);
  return <LangContext.Provider value={lang}>{children}</LangContext.Provider>;
}
